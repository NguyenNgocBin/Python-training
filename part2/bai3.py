scores = [8.5, 7.0, 9.0, 6.5, 8.0]

print(scores[0]) #In điểm đầu tiên.
print(scores[-1]) #In điểm cuối cùng.
print(scores[:3]) # In 3 điểm đầu.
print(scores.append(9.5)) # Thêm 9.5.
print(scores.remove(6.5)) # del scores[3] xoa theo index
print(scores.sort()) #Sắp xếp tăng dần.
print(len(scores)) #In số lượng phần tử.